// Generates packages/ui/src/styles/palette.css — the primitive colour scales.
// Every colour in the system comes from the few numbers below. Edit them, then run `pnpm tokens`.
// Scales follow the Radix 12-step model: 1–2 backgrounds, 3–5 fills, 6–8 borders, 9–10 solids, 11–12 text.

import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const OUT = resolve(dirname(fileURLToPath(import.meta.url)), "../../packages/ui/src/styles/palette.css");

// Brand: Navy (decided 2026-10-08). h = hue, c = peak chroma, l = lightness of the solid step (9).
const HUES = {
  navy: { h: 258, c: 0.14, l: 0.46 },
  // Status colours share Navy's deep, muted tone: similar lightness, low chroma.
  success: { h: 150, c: 0.105, l: 0.52 },
  warning: { h: 70, c: 0.11, l: 0.66 },
  danger: { h: 25, c: 0.13, l: 0.5 },
};

// Pure neutral: no hue, no chroma.
const GRAY = {
  light: [1, 0.985, 0.965, 0.945, 0.925, 0.905, 0.875, 0.81, 0.62, 0.57, 0.48, 0.17],
  dark: [0.13, 0.16, 0.195, 0.225, 0.255, 0.285, 0.33, 0.42, 0.52, 0.58, 0.72, 0.97],
};

const round = (n) => Math.round(n * 1000) / 1000;

function hueScale({ h, c, l }, mode) {
  let L;
  let M;
  if (mode === "light") {
    const l11 = Math.min(0.52, l - 0.1);
    L = [0.993, 0.98, 0.955, 0.93, 0.9, 0.865, 0.815, 0.75, l, l - 0.045, l11, Math.min(0.3, l11 - 0.07)];
    M = [0.03, 0.07, 0.14, 0.22, 0.3, 0.38, 0.5, 0.66, 1, 1, 0.9, 0.5];
  } else {
    // Steps 1–8 climb from the dark background to just below the solid, so order holds for deep hues.
    const top = Math.min(0.49, l - 0.07);
    const low = Array.from({ length: 8 }, (_, i) => 0.16 + (top - 0.16) * (i / 7) ** 1.15);
    L = [...low, l, Math.min(0.9, l + 0.05), Math.min(0.9, Math.max(0.78, l + 0.13)), 0.94];
    M = [0.1, 0.14, 0.25, 0.33, 0.4, 0.47, 0.56, 0.7, 1, 0.95, 0.75, 0.3];
  }
  return L.map((lv, i) => `oklch(${round(lv)} ${round(c * M[i])} ${h})`);
}

function block(mode) {
  const lines = [];
  GRAY[mode].forEach((lv, i) => {
    lines.push(`  --gray-${i + 1}: oklch(${lv} 0 0);`);
  });
  for (const [name, def] of Object.entries(HUES)) {
    lines.push("");
    hueScale(def, mode).forEach((v, i) => {
      lines.push(`  --${name}-${i + 1}: ${v};`);
    });
  }
  return lines.join("\n");
}

const n = HUES.navy;
const css = `/*
 * AUTO-GENERATED by scripts/tokens/generate-palette.mjs. Do not edit by hand.
 * Change the hue numbers in that script and run \`pnpm tokens\`.
 *
 * Primitive scales only. Components must use the semantic tokens in theme.css, never these directly.
 */

:root {
  --white: oklch(1 0 0);
  --black: oklch(0 0 0);

  /* Brand gradient endpoints: same hue and chroma, lightness ±0.055 around the solid ("Deeper") */
  --navy-gradient-top: oklch(${round(n.l + 0.055)} ${n.c} ${n.h});
  --navy-gradient-bottom: oklch(${round(n.l - 0.055)} ${n.c} ${n.h});
  --navy-pool: oklch(${round(n.l + 0.07)} ${n.c} ${n.h} / 0.9);
}

:root,
.light {
${block("light")}
}

.dark {
${block("dark")}
}
`;

writeFileSync(OUT, css);
console.log(`palette written to ${OUT}`);
